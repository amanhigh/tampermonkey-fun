/**
 * Escapes HTML special characters in a string to prevent XSS.
 * Order matters: ampersand must be escaped first to avoid double-encoding.
 */
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
